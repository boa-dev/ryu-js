#![allow(
    clippy::approx_constant,
    clippy::excessive_precision,
    clippy::cast_lossless,
    clippy::float_cmp,
    clippy::int_plus_one,
    clippy::non_ascii_literal,
    clippy::unreadable_literal,
    clippy::unseparated_literal_suffix
)]

fn f(f: f64, precision: u8) -> String {
    ryu_js::Buffer::new()
        .format_to_exponential(f, precision)
        .to_owned()
}

#[test]
fn nan() {
    for fraction_digits in 0..=100u8 {
        assert_eq!(f(f64::NAN, fraction_digits), "NaN");
    }
}

#[test]
fn infinity() {
    for fraction_digits in 0..=100u8 {
        assert_eq!(f(f64::INFINITY, fraction_digits), "Infinity");
    }
    for fraction_digits in 0..=100u8 {
        assert_eq!(f(f64::NEG_INFINITY, fraction_digits), "-Infinity");
    }
}

#[test]
fn positive_zero() {
    assert_eq!(f(0.0, 0), "0e+0");
    for precision in 1..=100u8 {
        let expected = "0".repeat(usize::from(precision));
        assert_eq!(f(0.0, precision), format!("0.{expected}e+0"));
    }
}

#[test]
fn negative_zero() {
    assert_eq!(f(-0.0, 0), "0e+0");
    for precision in 1..=100u8 {
        let expected = "0".repeat(usize::from(precision));
        assert_eq!(f(-0.0, precision), format!("0.{expected}e+0"));
    }
}

